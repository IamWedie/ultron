        var b = (string key, bool d) => json?[key]?.GetValue<bool>() ?? d;
        var ok = () => p.Connect() ? null : "Phone not reachable over ADB.";

        return name switch
        {
            "phone_screen_on" => ok() ?? p.ScreenOn(),
            "phone_screen_off" => ok() ?? p.ScreenOff(),
