    private static ToolDef NoArgs(string name, string desc = "") => new()
    {
        Name = name,
        Description = desc,
        Parameters = new JsonObject
        {
            ["type"] = "object",
            ["properties"] = new JsonObject(),
            ["required"] = new JsonArray(),
        },
    };

    private static ToolDef WithArgs(string name, string desc = "", params (string p, string t, bool req)[] args) => new()
    {
        Name = name,
        Description = desc,
        Parameters = new JsonObject
        {
            ["type"] = "object",
            ["properties"] = new JsonObject((IEnumerable<KeyValuePair<string, JsonNode?>>)args.Select(a => new KeyValuePair<string, JsonNode?>(a.p, new JsonObject { ["type"] = a.t }))),
            ["required"] = new JsonArray(args.Where(a => a.req).Select(a => (JsonNode)a.p).ToArray()),
        },
    };

